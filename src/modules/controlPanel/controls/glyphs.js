export const glyphBit = (char, x, y) =>
  (FONT[char.toUpperCase()] ?? '000000000000000')[y * 3 + x] === '1';

export function textParts(kit, text, x, y, pixel, z, look) {
  const out = [];
  [...text.toUpperCase()].forEach((char, index) => {
    for (let row = 0; row < 5; row += 1) {
      for (let col = 0; col < 3; col += 1) {
        if (glyphBit(char, col, row)) {
          const start = col;
          while (col < 2 && glyphBit(char, col + 1, row)) col += 1;
          const width = col - start + 1;
          out.push(
            kit.slab(
              x + (index * 4 + start + width / 2) * pixel,
              y - (row + 0.5) * pixel,
              (width * pixel) / 2,
              pixel * 0.43,
              z,
              z + 0.002,
              look
            )
          );
        }
      }
    }
  });
  return out;
}
