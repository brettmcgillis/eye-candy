export const DEFAULT_PLOTTER_PRESET = 'low';

export function normalizePlotterConfig(config = {}) {
  const hatchRotX = Number(config.rotX) || 0;
  const hatchRotY = Number(config.rotY) || 0;
  const hatchRotZ = Number(config.rotZ) || 0;
  const legacyAngleOffset = Number(config.secondHatchPassAngle);
  const crossHatchAngleOffset = Number.isFinite(legacyAngleOffset)
    ? legacyAngleOffset
    : 45;
  const hatchMaxSegments =
    Number(config.hatchMaxSegments) || Number(config.maxSegments) || 700;

  return {
    ...config,
    showCrossHatches:
      config.showCrossHatches ?? config.secondHatchPass ?? false,
    hatchStrokeWidthScale: config.hatchStrokeWidthScale ?? 1,
    hatchMaxSegments,
    crossHatchRotX: config.crossHatchRotX ?? hatchRotX + crossHatchAngleOffset,
    crossHatchRotY: config.crossHatchRotY ?? hatchRotY + crossHatchAngleOffset,
    crossHatchRotZ: config.crossHatchRotZ ?? hatchRotZ + crossHatchAngleOffset,
    crossHatchSpaceX: config.crossHatchSpaceX ?? config.spaceX ?? 8,
    crossHatchSpaceY: config.crossHatchSpaceY ?? config.spaceY ?? 8,
    crossHatchSpaceZ: config.crossHatchSpaceZ ?? config.spaceZ ?? 8,
    crossHatchInsetPixels:
      config.crossHatchInsetPixels ?? config.insetPixels ?? 2,
    crossHatchConnectHatches:
      config.crossHatchConnectHatches ?? config.connectHatches ?? false,
    crossHatchMaxSegments:
      Number(config.crossHatchMaxSegments) || hatchMaxSegments,
    crossHatchStrokeWidthScale: config.crossHatchStrokeWidthScale ?? 1,
    showPrimitivePoints: config.showPrimitivePoints ?? true,
    showPrimitiveLines: config.showPrimitiveLines ?? true,
    primitivePointRadius: config.primitivePointRadius ?? 1.2,
    primitivePointOpacity: config.primitivePointOpacity ?? 1,
    primitivePointDensityQuantization:
      config.primitivePointDensityQuantization ?? 1,
    primitivePointDensityMaxCount:
      Number(config.primitivePointDensityMaxCount) || 2000,
    primitiveLineStrokeWidthScale: config.primitiveLineStrokeWidthScale ?? 1,
    primitiveLineOpacity: config.primitiveLineOpacity ?? 1,
    primitiveLineDensityQuantization:
      config.primitiveLineDensityQuantization ?? 0.5,
    primitiveLineDensityMaxSegments:
      Number(config.primitiveLineDensityMaxSegments) || 3000,
    primitiveLineDensityMinLength: config.primitiveLineDensityMinLength ?? 0.75,
  };
}

