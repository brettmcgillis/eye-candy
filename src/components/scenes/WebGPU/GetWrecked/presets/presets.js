// Preset snapshots — keys match the Leva schema 1:1 (docs/scene-conventions.md
// §9). Every preset carries the full key set, so switching between them never
// leaks a stale value from the previously selected one.
//
// The batch is deliberately mechanical: Pristine is the scene at rest — the lot
// lit, every vehicle intact, every technique off but holding a tuned amount —
// and each preset after it is Pristine with exactly one thing switched on. That
// makes them a showcase you can step through one at a time, and it keeps the
// amounts in one place: retune a value in Pristine and all of them inherit it,
// since none of the variants override anything but their own toggle.
//
// None of these is a no-op — every technique's Pristine amount is already
// non-zero. The last two entries are the exceptions to the one-toggle rule:
// Slit Scan & Pixel Bleed is a deliberate combination, and Theatre hands the
// scene (and the camera) to the sequencer rather than enabling an effect.

