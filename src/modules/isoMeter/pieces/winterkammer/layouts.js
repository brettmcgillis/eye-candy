export default function rollLayout(master) {
  const layout = LAYOUTS[master.randomIntExcl(4)];
  const kinds = layout.types.map((type) => {
    if (Array.isArray(type)) return KINDS[master.roll() < type[1] ? 0 : 4];
    return KINDS[type];
  });
  return { ...layout, count: kinds.length, kinds };
}
