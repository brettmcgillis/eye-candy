// Preset snapshots — keys match the Leva schema 1:1 (docs/scene-conventions.md
// §9). Every preset defines the full glitch key set so switching between
// presets never leaks a stale value from the previously selected one.
//
// Each technique's "Enabled" toggle is the single source of truth for
// whether it's visible — there's no separate blend slider to also remember
// to raise. Cut & Paste, Hopscotch, Resolution Loss and Torn Open each have
// their own independent Density (how many vertices/blocks/cells
// participate) — so any one technique can be dialed from a handful of
// scattered spots up to full coverage without the others changing.
//
// "Wrong Direction" pushes PBR params out of their physically-valid range
// (negative roughness/metalness multipliers, subtractive emissive, inverted
// lighting normals) rather than misdirecting vertex/UV data like the other
// techniques — same "Enabled gates it to a no-op" shape, multiplier 1 /
// intensity 0 / invert 0 being the identity (uncorrupted) values.
//
// "Scroll Tear" lives on the car's own geometry/UV (Tear Position is
// normalized 0-1 against the car's actual height), not the screen — see
// utils/glitchMaterial.js. "Resolution Loss" and "Torn Open" derive their
// masks procedurally (no baked per-vertex data), so they're fully
// independent of every permutation-based technique's density too.
//
// cameraMode is included explicitly (docs/scene-conventions.md §10) so
// Orbit stays the enforced default: without it here, the Presets folder's
// "reset" button and preset switches would never restore Orbit if the mode
// got changed by hand.
