// its preset follows. A technique's parameters are inert while it is disabled,
// which is what lets all fourteen baselines coexist in one snapshot.
//
// The last two entries are the exceptions to the one-toggle rule: Slit Scan &
// Pixel Bleed is a deliberate combination, and Theatre hands the scene (and the
// camera) to the sequencer rather than enabling an effect.

